-- Deal Capital gets its own funnel (DealFeedbackStage) instead of sharing the
-- fund-raising FundraisingStage. Existing rows are carried over:
--   NOT_STARTED -> BRAINSTORM
--   OUTREACH_SENT -> OUTREACH_SENT
--   INITIAL_INTEREST / MEETING_OCCURRED / ACTIVE_PROSPECT -> ENGAGEMENT_SHOWN
--   FINAL_CLOSE_POTENTIAL / DUE_DILIGENCE -> DUE_DILIGENCE
--   COMMITTED -> TERM_SHEET_COMMITTED
--   PASSED_OPEN / DECLINE -> DECLINED
-- (The 62 ACTIVE_PROSPECT rows are then re-sorted entry by entry in a data
-- script, using their notes.)

-- CreateEnum
CREATE TYPE "DealFeedbackStage" AS ENUM ('BRAINSTORM', 'OUTREACH_SENT', 'ENGAGEMENT_SHOWN', 'DUE_DILIGENCE', 'DECLINED', 'TERM_SHEET_COMMITTED');

-- AlterTable
ALTER TABLE "DealFeedback" ALTER COLUMN "status" DROP DEFAULT;
ALTER TABLE "DealFeedback" ALTER COLUMN "status" TYPE "DealFeedbackStage" USING (
  CASE "status"::text
    WHEN 'NOT_STARTED' THEN 'BRAINSTORM'
    WHEN 'OUTREACH_SENT' THEN 'OUTREACH_SENT'
    WHEN 'INITIAL_INTEREST' THEN 'ENGAGEMENT_SHOWN'
    WHEN 'MEETING_OCCURRED' THEN 'ENGAGEMENT_SHOWN'
    WHEN 'ACTIVE_PROSPECT' THEN 'ENGAGEMENT_SHOWN'
    WHEN 'FINAL_CLOSE_POTENTIAL' THEN 'DUE_DILIGENCE'
    WHEN 'DUE_DILIGENCE' THEN 'DUE_DILIGENCE'
    WHEN 'COMMITTED' THEN 'TERM_SHEET_COMMITTED'
    WHEN 'PASSED_OPEN' THEN 'DECLINED'
    WHEN 'DECLINE' THEN 'DECLINED'
  END::"DealFeedbackStage"
);
ALTER TABLE "DealFeedback" ALTER COLUMN "status" SET DEFAULT 'BRAINSTORM';
